package snmp

import (
	"crypto/sha1"
	"encoding/hex"
	"fmt"
	"strings"
)

// ZabbixTemplate renders deploy/zabbix/template_nsrelay_snmp.yaml (Zabbix 7.0 export format, imports into 7.x
// and 8): the same values as the HTTP template, read over SNMP. Generated from the object list like the MIB
// (`nsrelay snmp-mib -zabbix`). Never link both templates to one host (duplicate triggers).

// zabbixNS is the uuid5 namespace of tools/gen_zabbix_template.py, so shared objects (the template group) get
// the same UUID in both templates.
var zabbixNS = [16]byte{0x6f, 0x1d, 0x3c, 0x52, 0x0d, 0x1e, 0x4c, 0x55, 0x9a, 0x43, 0x6e, 0x5c, 0x1a, 0x2b, 0x7d, 0x10}

// zuuid is uuid5(zabbixNS, name) with the version/variant bits of a UUIDv4 (Zabbix only accepts v4 syntax).
func zuuid(name string) string {
	h := sha1.New()
	h.Write(zabbixNS[:])
	h.Write([]byte(name))
	b := h.Sum(nil)[:16]
	b[6] = (b[6] & 0x0f) | 0x40
	b[8] = (b[8] & 0x3f) | 0x80
	return hex.EncodeToString(b)
}

func zq(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

const zTemplate = "Netsession Relay SNMP"

// ZabbixTemplate returns the template as YAML.
func ZabbixTemplate() string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	scalar := func(name string) Scalar {
		for _, s := range Scalars {
			if s.Name == name {
				return s
			}
		}
		panic(name)
	}
	type trig struct{ expr, name, prio, desc string }
	item := func(label, key, oid, vt, units string, rate bool, triggers ...trig) {
		w("        - uuid: %s", zuuid("snmp-item:"+key))
		w("          name: %s", zq(label))
		w("          type: SNMP_AGENT")
		w("          snmp_oid: %s", zq("get["+oid+"]"))
		w("          key: %s", zq(key))
		w("          delay: 1m")
		w("          history: 30d")
		w("          value_type: %s", vt)
		if vt == "CHAR" {
			w("          trends: '0'")
		}
		if units != "" {
			w("          units: %s", zq(units))
		}
		if rate {
			w("          preprocessing:")
			w("            - type: CHANGE_PER_SECOND")
			w("              parameters:")
			w("                - ''")
		}
		w("          tags:")
		w("            - tag: component")
		w("              value: relay")
		if len(triggers) > 0 {
			w("          triggers:")
			for i, t := range triggers {
				w("            - uuid: %s", zuuid(fmt.Sprintf("snmp-trigger:%s:%d", key, i)))
				w("              expression: %s", zq(strings.ReplaceAll(t.expr, "KEY", "/"+zTemplate+"/"+key)))
				w("              name: %s", zq(t.name))
				w("              priority: %s", t.prio)
				w("              description: %s", zq(t.desc))
			}
		}
	}
	so := func(name string) string { return OID(scalar(name).Sub) + ".0" }

	w("zabbix_export:")
	w("  version: '7.0'")
	w("  template_groups:")
	w("    - uuid: %s", zuuid("group:Templates/Applications"))
	w("      name: Templates/Applications")
	w("  templates:")
	w("    - uuid: %s", zuuid("snmp-template"))
	w("      template: %s", zq(zTemplate))
	w("      name: %s", zq(zTemplate))
	w("      description: |")
	w("        Netsession Relay over SNMP (NETSESSION-RELAY-MIB). Alternative to the HTTP template \"Netsession Relay\":")
	w("        never link both to one host. Needs an SNMP interface (v3 authPriv recommended) on the host.")
	w("        Generated by `nsrelay snmp-mib -zabbix`, do not edit by hand.")
	w("      groups:")
	w("        - name: Templates/Applications")
	w("      items:")
	item("Relay: Engine erreichbar", "nsrelay.snmp.engine.up", so("nsRelayEngineUp"), "UNSIGNED", "", false,
		trig{"last(KEY)=2", "Relay: Engine antwortet nicht", "HIGH", "nsRelayEngineUp ist false: die Web-Rolle erreicht die Engine nicht."})
	item("Relay: Betriebsart", "nsrelay.snmp.mode", so("nsRelayMode"), "UNSIGNED", "", false)
	item("Relay: Standby (zweites Relay)", "nsrelay.snmp.standby", so("nsRelayStandby"), "UNSIGNED", "", false,
		trig{"last(KEY)=1", "Relay: im Standby, ein anderes Relay ist aktiv", "AVERAGE", "Der Wächter hat ein zweites aktives Relay gesehen."})
	item("Relay: leitet weiter", "nsrelay.snmp.sending", so("nsRelaySending"), "UNSIGNED", "", false)
	item("Relay: Engine-Version", "nsrelay.snmp.engine.version", so("nsRelayEngineVersion"), "CHAR", "", false)
	item("Relay: Engine-Laufzeit", "nsrelay.snmp.uptime", so("nsRelayEngineUptime"), "UNSIGNED", "", false)
	item("Relay: Netze", "nsrelay.snmp.vlans", so("nsRelayVlanCount"), "UNSIGNED", "", false)
	item("Relay: Regeln", "nsrelay.snmp.rules", so("nsRelayRuleCount"), "UNSIGNED", "", false)
	item("Relay: offene Alarme", "nsrelay.snmp.alarms.active", so("nsRelayAlarmsActive"), "UNSIGNED", "", false)
	item("Relay: Monitoring-Ziele mit Fehler", "nsrelay.snmp.outputs.failing", so("nsRelayOutputsFailing"), "UNSIGNED", "", false,
		trig{"last(KEY)>0", "Relay: Monitoring-Ziel nicht erreichbar", "WARNING", "Ein Syslog-, OpenTelemetry- oder SNMP-Ziel nimmt seit 2 Minuten nichts an."})
	item("Relay: Selbsttest-Befunde", "nsrelay.snmp.selftest", so("nsRelaySelfTestFindings"), "UNSIGNED", "", false,
		trig{"last(KEY)>0", "Relay: Selbsttest meldet Befunde am Host", "INFO", "Details auf der System-Seite."})
	item("Relay: empfangen pro Sekunde", "nsrelay.snmp.rx.rate", so("nsRelayRxFrames"), "FLOAT", "fps", true)
	item("Relay: gesendet pro Sekunde", "nsrelay.snmp.sent.rate", so("nsRelaySentFrames"), "FLOAT", "fps", true)
	alarmTrig := map[string]trig{
		"foreign_relay": {"last(KEY)>0", "Relay: fremdes Relay aktiv", "HIGH", "Ein anderes Gerät leitet dieselben Broadcasts weiter."},
		"loop":          {"last(KEY)>0", "Relay: Schleife erkannt", "HIGH", "Dasselbe Paket kam auf mehreren VLANs an."},
		"storm":         {"last(KEY)>0", "Relay: Sturm-Bremse hat eine Regel pausiert", "AVERAGE", "Über 5000 Pakete/s auf einem Port."},
		"dual_active":   {"last(KEY)>0", "Relay: zweites aktives Relay entdeckt", "HIGH", "Zwei Relays für dieselben Netze."},
		"vlan_silent":   {"last(KEY)>0", "Relay: Netz ohne Broadcasts seit 10 Minuten", "WARNING", "Während eines aktiven Events kam auf einem Netz nichts an."},
		"engine_down":   {"last(KEY)>0", "Relay: Engine weg (SNMP)", "HIGH", "Die Web-Rolle erreicht die Engine nicht."},
	}
	for i, k := range alarmKindsSNMP {
		item("Relay: Alarm "+k+" offen", "nsrelay.snmp.alarm.active["+k+"]", fmt.Sprintf("%s.1.3.%d", OID("1.4"), i+1), "UNSIGNED", "", false, alarmTrig[k])
	}
	for _, n := range Notifications[:3] {
		// snmptrapd without our MIB writes "SNMPv2-SMI::enterprises.32473.1.1.0.1"; (\s|$) keeps .0.1 from
		// matching .0.10
		sym := "enterprises." + strings.TrimPrefix(OID(n.Sub), "1.3.6.1.4.1.")
		key := `snmptrap["` + strings.ReplaceAll(sym, ".", `\.`) + `(\s|$)"]`
		w("        - uuid: %s", zuuid("snmp-trap:"+n.Name))
		w("          name: %s", zq("Relay: Trap "+n.Name))
		w("          type: SNMP_TRAP")
		w("          key: %s", zq(key))
		w("          delay: '0'")
		w("          history: 30d")
		w("          value_type: LOG")
		w("          trends: '0'")
		w("          description: %s", zq(n.Desc+" Braucht snmptrapd (ohne geladene MIB) und am Host eine SNMP-Schnittstelle mit der Absender-IP des Relays."))
		w("          tags:")
		w("            - tag: component")
		w("              value: trap")
	}
	w("      discovery_rules:")
	w("        - uuid: %s", zuuid("snmp-lld:vlan"))
	w("          name: 'Relay: Netze (VLANs) über SNMP'")
	w("          type: SNMP_AGENT")
	w("          snmp_oid: %s", zq("discovery[{#VLANNAME},"+OID("1.5.1.2")+",{#VLANGROUP},"+OID("1.5.1.3")+"]"))
	w("          key: nsrelay.snmp.vlan.discovery")
	w("          delay: 1h")
	w("          lifetime: 7d")
	w("          item_prototypes:")
	type proto struct {
		label, key string
		col        int
		vt, units  string
		rate       bool
		tr         *trig
	}
	for _, p := range []proto{
		{"Netz {#VLANNAME} (VLAN {#SNMPINDEX}): empfangen pro Sekunde", "nsrelay.snmp.vlan.in.rate[{#SNMPINDEX}]", 5, "FLOAT", "fps", true, nil},
		{"Netz {#VLANNAME} (VLAN {#SNMPINDEX}): gesendet pro Sekunde", "nsrelay.snmp.vlan.out.rate[{#SNMPINDEX}]", 6, "FLOAT", "fps", true, nil},
		{"Netz {#VLANNAME} (VLAN {#SNMPINDEX}): Sekunden ohne Empfang", "nsrelay.snmp.vlan.silent_s[{#SNMPINDEX}]", 8, "UNSIGNED", "s", false, nil},
		{"Netz {#VLANNAME} (VLAN {#SNMPINDEX}): still", "nsrelay.snmp.vlan.silent[{#SNMPINDEX}]", 9, "UNSIGNED", "", false,
			&trig{"last(KEY)=1", "Relay: Netz {#VLANNAME} (VLAN {#SNMPINDEX}) still seit 10 Minuten", "WARNING", "Während eines aktiven Events kam auf diesem Netz kein Broadcast an."}},
	} {
		w("            - uuid: %s", zuuid("snmp-proto:"+p.key))
		w("              name: %s", zq(p.label))
		w("              type: SNMP_AGENT")
		w("              snmp_oid: %s", zq(fmt.Sprintf("%s.1.%d.{#SNMPINDEX}", OID("1.5"), p.col)))
		w("              key: %s", zq(p.key))
		w("              delay: 1m")
		w("              history: 30d")
		w("              value_type: %s", p.vt)
		if p.units != "" {
			w("              units: %s", zq(p.units))
		}
		if p.rate {
			w("              preprocessing:")
			w("                - type: CHANGE_PER_SECOND")
			w("                  parameters:")
			w("                    - ''")
		}
		w("              tags:")
		w("                - tag: vlan")
		w("                  value: '{#SNMPINDEX} {#VLANNAME}'")
		if p.tr != nil {
			w("              trigger_prototypes:")
			w("                - uuid: %s", zuuid("snmp-trigproto:"+p.key))
			w("                  expression: %s", zq(strings.ReplaceAll(p.tr.expr, "KEY", "/"+zTemplate+"/"+p.key)))
			w("                  name: %s", zq(p.tr.name))
			w("                  priority: %s", p.tr.prio)
			w("                  description: %s", zq(p.tr.desc))
		}
	}
	w("      tags:")
	w("        - tag: class")
	w("          value: application")
	w("        - tag: target")
	w("          value: nsrelay")
	return b.String()
}
