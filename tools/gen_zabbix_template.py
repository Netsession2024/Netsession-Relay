#!/usr/bin/env python3
"""Generate deploy/zabbix/template_nsrelay.yaml (Zabbix 7.0 export format, imports into 7.x and 8).

UUIDs are derived from the item keys (uuid5), so regenerating gives the same file and Zabbix updates the
template in place on re-import. Every JSONPath used here is checked against the real report by
internal/monitor/template_test.go.

    python -I tools/gen_zabbix_template.py
"""
import pathlib
import uuid

T = "Netsession Relay"
NS = uuid.UUID("6f1d3c52-0d1e-4c55-9a43-6e5c1a2b7d10")
OUT = pathlib.Path(__file__).resolve().parent.parent / "deploy" / "zabbix" / "template_nsrelay.yaml"
L = []
w = L.append


def u(name):
    # Zabbix wants UUIDv4 syntax: take uuid5 bytes and set the version/variant bits of v4.
    b = bytearray(uuid.uuid5(NS, name).bytes)
    b[6] = (b[6] & 0x0F) | 0x40
    b[8] = (b[8] & 0x3F) | 0x80
    return uuid.UUID(bytes=bytes(b)).hex


def q(s):
    return "'" + s.replace("'", "''") + "'"


def dep(name, key, path, vt="UNSIGNED", units="", triggers=(), tag="relay", change=False, default=None, desc=""):
    w(f"        - uuid: {u('item:' + key)}")
    w(f"          name: {q(name)}")
    w("          type: DEPENDENT")
    w(f"          key: {q(key)}")
    w("          delay: '0'")
    w("          history: 30d")
    w(f"          value_type: {vt}")
    if vt in ("CHAR", "TEXT"):
        w("          trends: '0'")
    if units:
        w(f"          units: {q(units)}")
    if desc:
        w(f"          description: {q(desc)}")
    w("          preprocessing:")
    w("            - type: JSONPATH")
    w("              parameters:")
    w(f"                - {q(path)}")
    if default is not None:
        w("              error_handler: CUSTOM_VALUE")
        w(f"              error_handler_params: {q(default)}")
    if change:
        w("            - type: CHANGE_PER_SECOND")
        w("              parameters:")
        w("                - ''")
    if vt in ("CHAR", "TEXT"):
        w("            - type: DISCARD_UNCHANGED_HEARTBEAT")
        w("              parameters:")
        w("                - 1h")
    w("          master_item:")
    w("            key: nsrelay.monitoring")
    w("          tags:")
    w("            - tag: component")
    w(f"              value: {tag}")
    if triggers:
        w("          triggers:")
        for expr, tname, prio, tdesc in triggers:
            w(f"            - uuid: {u('trigger:' + key)}")
            w(f"              expression: {q(expr.replace('KEY', f'/{T}/{key}'))}")
            w(f"              name: {q(tname)}")
            w(f"              priority: {prio}")
            if tdesc:
                w(f"              description: {q(tdesc)}")


def proto(name, key, field, vt="UNSIGNED", units="", change=False, trig=None):
    w(f"            - uuid: {u('proto:' + key)}")
    w(f"              name: {q(name)}")
    w("              type: DEPENDENT")
    w(f"              key: {q(key)}")
    w("              delay: '0'")
    w("              history: 30d")
    w(f"              value_type: {vt}")
    if units:
        w(f"              units: {q(units)}")
    w("              preprocessing:")
    w("                - type: JSONPATH")
    w("                  parameters:")
    w(f"                    - {q('$.vlan_list[?(@.vid=={#VID})].' + field + '.first()')}")
    if change:
        w("                - type: CHANGE_PER_SECOND")
        w("                  parameters:")
        w("                    - ''")
    w("              master_item:")
    w("                key: nsrelay.monitoring")
    w("              tags:")
    w("                - tag: vlan")
    w("                  value: '{#VID} {#NAME}'")
    if trig:
        expr, tname, prio, tdesc = trig
        w("              trigger_prototypes:")
        w(f"                - uuid: {u('trigproto:' + key)}")
        w(f"                  expression: {q(expr.replace('KEY', f'/{T}/{key}'))}")
        w(f"                  name: {q(tname)}")
        w(f"                  priority: {prio}")
        w(f"                  description: {q(tdesc)}")


def main():
    w("zabbix_export:")
    w("  version: '7.0'")
    w("  template_groups:")
    w(f"    - uuid: {u('group:Templates/Applications')}")
    w("      name: Templates/Applications")
    w("  templates:")
    w(f"    - uuid: {u('template')}")
    w(f"      template: {q(T)}")
    w(f"      name: {q(T)}")
    w("      description: |")
    w("        Netsession Relay (UDP broadcast relay for LAN games).")
    w("        Polls {$NSRELAY.URL}/api/v1/monitoring every 30 s (HTTP agent). The token is created on the")
    w("        System page of the relay. Set {$NSRELAY.URL} and {$NSRELAY.TOKEN} on the host.")
    w("        Generated by tools/gen_zabbix_template.py, do not edit by hand.")
    w("      groups:")
    w("        - name: Templates/Applications")
    w("      items:")
    w(f"        - uuid: {u('item:nsrelay.monitoring')}")
    w("          name: 'Relay: monitoring JSON'")
    w("          type: HTTP_AGENT")
    w("          key: nsrelay.monitoring")
    w("          delay: 30s")
    w("          history: 1h")
    w("          value_type: TEXT")
    w("          trends: '0'")
    w("          url: '{$NSRELAY.URL}/api/v1/monitoring'")
    w("          headers:")
    w("            - name: Authorization")
    w("              value: 'Bearer {$NSRELAY.TOKEN}'")
    w("          timeout: 5s")
    w("          tags:")
    w("            - tag: component")
    w("              value: raw")
    w("          triggers:")
    w(f"            - uuid: {u('trigger:nsrelay.monitoring')}")
    w(f"              expression: 'nodata(/{T}/nsrelay.monitoring,3m)=1'")
    w("              name: 'Relay: Web-Teil antwortet nicht'")
    w("              priority: HIGH")
    w("              description: 'Seit 3 Minuten keine Antwort von /api/v1/monitoring: Web-Container, Token oder VM prüfen.'")

    dep("Relay: Engine erreichbar", "nsrelay.engine.up", "$.engine_up",
        triggers=[("last(KEY)=0", "Relay: Engine antwortet nicht", "HIGH",
                   "Die Web-Rolle erreicht die Engine nicht über den Unix-Socket. Engine-Container prüfen.")])
    dep("Relay: Betriebsart", "nsrelay.mode", "$.mode", vt="CHAR", desc="active, observe, paused oder leer vor dem ersten Stand.")
    dep("Relay: Standby (zweites Relay)", "nsrelay.standby", "$.standby",
        triggers=[("last(KEY)=1", "Relay: im Standby, ein anderes Relay ist aktiv", "AVERAGE",
                   "Der Wächter hat ein zweites aktives Relay gesehen und dieses angehalten.")])
    dep("Relay: leitet weiter", "nsrelay.sending", "$.sending")
    dep("Relay: Event aktiv", "nsrelay.event.active", "$.event_active")
    dep("Relay: Engine-Version", "nsrelay.engine.version", "$.engine_version", vt="CHAR")
    dep("Relay: Engine-Laufzeit", "nsrelay.uptime", "$.uptime_s", units="uptime")
    dep("Relay: Stand (Hash)", "nsrelay.snapshot", "$.snapshot", vt="CHAR")
    dep("Relay: Netze", "nsrelay.vlans", "$.vlans")
    dep("Relay: Regeln", "nsrelay.rules", "$.rules")
    dep("Relay: empfangen pro Sekunde", "nsrelay.rx.rate", "$.rx_per_s", units="fps")
    dep("Relay: gesendet pro Sekunde", "nsrelay.sent.rate", "$.sent_per_s", units="fps")
    dep("Relay: offene Alarme", "nsrelay.alarms.active", "$.alarms_active")
    dep("Relay: Selbsttest-Befunde", "nsrelay.selftest", "$.self_test_findings",
        triggers=[("last(KEY)>0", "Relay: Selbsttest meldet Befunde am Host", "INFO",
                   "Details auf der System-Seite (z. B. ip_forward, rp_filter).")])
    dep("Relay: Monitoring-Ziele", "nsrelay.outputs.total", "$.outputs_total", default="0")
    dep("Relay: Monitoring-Ziele mit Fehler", "nsrelay.outputs.failing", "$.outputs_failing", default="0",
        triggers=[("last(KEY)>0", "Relay: Monitoring-Ziel nicht erreichbar", "WARNING",
                   "Ein Syslog-, OpenTelemetry- oder SNMP-Ziel nimmt seit 2 Minuten nichts an. Details: System, Monitoring.")])
    dep("Relay: verworfene Meldungen", "nsrelay.outputs.dropped", "$.outputs_dropped", default="0")
    for r in ["loop", "rate", "foreign_relay", "src_subnet", "auto_paused", "unknown_port"]:
        dep(f"Relay: verworfen {r} pro Sekunde", f"nsrelay.drops.rate[{r}]", f"$.drops.{r}", vt="FLOAT", units="fps",
            change=True, default="0", tag="drops")

    alarms = {
        "foreign_relay": ("Relay: fremdes Relay aktiv ({ITEM.LASTVALUE2})", "HIGH",
                          "Ein anderes Gerät leitet dieselben Broadcasts weiter (z. B. eine alte OPNsense-Box). Im Modus Beobachten erwartet."),
        "loop": ("Relay: Schleife erkannt ({ITEM.LASTVALUE2})", "HIGH",
                 "Dasselbe Paket kam auf mehreren VLANs an. Zweites Relay oder Brücke zwischen Netzen suchen."),
        "storm": ("Relay: Sturm-Bremse hat eine Regel pausiert ({ITEM.LASTVALUE2})", "AVERAGE",
                  "Über 5000 Pakete/s, die lauteste Regel pausiert 60 s."),
        "dual_active": ("Relay: zweites aktives Relay entdeckt", "HIGH", "Zwei Relays für dieselben Netze. Eins muss aus."),
        "vlan_silent": ("Relay: Netz ohne Broadcasts seit 10 Minuten ({ITEM.LASTVALUE2})", "WARNING",
                        "Während eines aktiven Events kam auf einem Netz nichts an. Trunk, VLAN-Tag oder Switch-Port prüfen."),
    }
    for kind, (tname, prio, tdesc) in alarms.items():
        keys_key = f"nsrelay.alarm.keys[{kind}]"
        dep(f"Relay: Alarm {kind} betroffen", keys_key, f"$.alarms.{kind}.keys", vt="CHAR", tag="alarm", default="[]")
        # the second function only pulls the affected keys into the trigger name ({ITEM.LASTVALUE2})
        dep(f"Relay: Alarm {kind} offen", f"nsrelay.alarm.active[{kind}]", f"$.alarms.{kind}.active", tag="alarm",
            default="0", triggers=[(f"last(KEY)>0 and length(last(/{T}/{keys_key}))>=0", tname, prio, tdesc)])

    w("      discovery_rules:")
    w(f"        - uuid: {u('lld:nsrelay.vlan.discovery')}")
    w("          name: 'Relay: Netze (VLANs)'")
    w("          type: DEPENDENT")
    w("          key: nsrelay.vlan.discovery")
    w("          delay: '0'")
    w("          lifetime: 7d")
    w("          item_prototypes:")
    proto("Netz {#NAME} (VLAN {#VID}): empfangen pro Sekunde", "nsrelay.vlan.in.rate[{#VID}]", "in_per_s", units="fps")
    proto("Netz {#NAME} (VLAN {#VID}): gesendet pro Sekunde", "nsrelay.vlan.out.rate[{#VID}]", "out", vt="FLOAT",
          units="fps", change=True)
    proto("Netz {#NAME} (VLAN {#VID}): Sekunden ohne Empfang", "nsrelay.vlan.silent_s[{#VID}]", "silent_s", units="s")
    proto("Netz {#NAME} (VLAN {#VID}): still", "nsrelay.vlan.silent[{#VID}]", "silent",
          trig=("last(KEY)=1", "Relay: Netz {#NAME} (VLAN {#VID}) still seit 10 Minuten", "WARNING",
                "Während eines aktiven Events kam auf diesem Netz kein Broadcast an."))
    w("          master_item:")
    w("            key: nsrelay.monitoring")
    w("          lld_macro_paths:")
    for m, p in [("{#VID}", "$.vid"), ("{#NAME}", "$.name"), ("{#GROUP}", "$.group")]:
        w(f"            - lld_macro: {q(m)}")
        w(f"              path: {q(p)}")
    w("          preprocessing:")
    w("            - type: JSONPATH")
    w("              parameters:")
    w("                - $.vlan_list")
    w("      tags:")
    w("        - tag: class")
    w("          value: application")
    w("        - tag: target")
    w("          value: nsrelay")
    w("      macros:")
    w("        - macro: '{$NSRELAY.TOKEN}'")
    w("          type: SECRET_TEXT")
    w("          description: 'Token von der System-Seite des Relays (Abschnitt Monitoring).'")
    w("        - macro: '{$NSRELAY.URL}'")
    w("          value: 'http://127.0.0.1:8080'")
    w("          description: 'Basis-URL der Relay-Weboberfläche (MGMT-Adresse und Port), ohne Schrägstrich am Ende.'")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(OUT)


if __name__ == "__main__":
    main()
